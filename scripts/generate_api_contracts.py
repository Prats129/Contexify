"""Generate client wire types from Pydantic schemas without importing the app.

Run with backend/venv/Scripts/python.exe -B scripts/generate_api_contracts.py.
Use --check in verification to reject stale generated files without writing them.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from pydantic.json_schema import models_json_schema  # noqa: E402

from app.schemas import chat, document, media, session, user  # noqa: E402

MODELS = (
    chat.ChatRequest,
    chat.MessageAcknowledgement,
    chat.StreamChunkResponse,
    document.DocumentUploadResponse,
    document.DocumentListResponse,
    document.DocumentChunksResponse,
    media.PaginatedAssetsResponse,
    media.AssetDeleteResponse,
    session.ChatSessionCreate,
    session.ChatSessionUpdate,
    session.TitleUpdatePayload,
    session.ModeUpdatePayload,
    session.PinUpdatePayload,
    session.SessionHistoryResponse,
    session.PaginatedChatSessionsResponse,
    user.UserRegisterRequest,
    user.UserLoginRequest,
    user.UserProfileUpdateRequest,
    user.UserPasswordChangeRequest,
    user.SendOtpRequest,
    user.SendOtpResponse,
    user.VerifyOtpLoginRequest,
    user.ResetPasswordWithOtpRequest,
    user.GoogleAuthRequest,
    user.UserResponse,
    user.AuthResponse,
    user.GuestAuthResponse,
)


def typescript(schema: dict) -> str:
    """Translate only schema forms used by our contracts; reject unknown forms."""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "anyOf" in schema:
        return " | ".join(typescript(part) for part in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            required = set(schema.get("required", []))
            fields = [
                f"  {json.dumps(name)}{'' if name in required else '?'}: {typescript(value)};"
                for name, value in schema["properties"].items()
            ]
            return "{\n" + "\n".join(fields) + "\n}"
        extra = schema.get("additionalProperties", True)
        return f"Record<string, {typescript(extra) if isinstance(extra, dict) else 'unknown'}>"
    scalar = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }
    if kind in scalar:
        return scalar[kind]
    if not schema or set(schema) <= {"title", "description", "default"}:
        return "unknown"
    raise ValueError(f"Unsupported contract schema: {schema}")


def render() -> str:
    _, schema = models_json_schema([(model, "validation") for model in MODELS])
    definitions = schema["$defs"]
    return (
        "// Generated by scripts/generate_api_contracts.py. Do not edit.\n"
        "// Wire contracts only; optimistic state and UI callbacks belong in index.ts.\n\n"
        + "\n\n".join(
            f"export type {name} = {typescript(value)};"
            for name, value in sorted(definitions.items())
        )
        + "\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    stale = []
    for platform in ("frontend", "mobile"):
        target = ROOT / platform / "src/types/api-contracts.ts"
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != generated:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(generated, encoding="utf-8")
    if stale:
        print("Stale API contracts: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("API contracts " + ("verified." if args.check else "generated."))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
