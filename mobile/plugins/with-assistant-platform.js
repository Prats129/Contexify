const fs = require("node:fs");
const path = require("node:path");
const configureAlarmWidget = require("./with-assistant-alarm-widget");
const {
  withInfoPlist,
  withXcodeProject,
  IOSConfig,
} = require("expo/config-plugins");

const marker = "// Generated by Contexify with-assistant-platform.\n";
const shortcuts = `${marker}import AppIntents
import AssistantPlatform

@available(iOS 17.0, *)
struct ContexifyAssistantPackage: AppIntentsPackage {
  static var includedPackages: [any AppIntentsPackage.Type] { [AssistantPlatformIntentsPackage.self] }
}

@available(iOS 17.0, *)
struct ContexifyAssistantShortcuts: AppShortcutsProvider {
  static var appShortcuts: [AppShortcut] {
    AppShortcut(intent: OpenContexifyAssistantIntent(),
      phrases: ["Open assistant in \\(.applicationName)"],
      shortTitle: "Open Assistant", systemImageName: "bubble.left.and.text.bubble.right")
  }
}
`;

/** No private Calendar/Reminders read permission or AlarmKit entitlement. */
module.exports = function withAssistantPlatform(
  config,
  { enabled = false, voiceEnabled = false } = {},
) {
  if (typeof enabled !== "boolean" || typeof voiceEnabled !== "boolean")
    throw new Error("Assistant platform build options must be booleans.");
  config = withInfoPlist(config, (mod) => {
    mod.modResults.ContexifyAssistantExtensionsEnabled = enabled;
    mod.modResults.ContexifyAssistantVoiceEnabled = voiceEnabled;
    mod.modResults.ContexifyAssistantCountdownWidget = enabled;
    if (enabled) {
      mod.modResults.NSAlarmKitUsageDescription =
        "Ring alarms and timers you review and approve in Contexify. AlarmKit may sound through silent mode and Focus.";
      mod.modResults.NSSupportsLiveActivities = true;
    } else {
      delete mod.modResults.NSAlarmKitUsageDescription;
    }
    if (voiceEnabled) {
      mod.modResults.NSMicrophoneUsageDescription ??=
        "Use the microphone only when you request on-device Assistant speech.";
      mod.modResults.NSSpeechRecognitionUsageDescription ??=
        "Recognize your requested English command on this iPhone. Contexify does not use remote speech recognition.";
    }
    return mod;
  });
  return withXcodeProject(config, (mod) => {
    configureAlarmWidget(mod, enabled);
    const name = mod.modRequest.projectName;
    if (!name || path.basename(name) !== name)
      throw new Error("iOS project name is unavailable.");
    const filename = "ContexifyAssistantShortcuts.swift";
    const target = path.join(
      mod.modRequest.platformProjectRoot,
      name,
      filename,
    );
    const exists = fs.existsSync(target);
    if (!enabled && !exists) return mod;
    if (exists && !fs.readFileSync(target, "utf8").startsWith(marker))
      throw new Error(
        "Refusing to replace a manually maintained Assistant shortcuts file.",
      );
    fs.mkdirSync(path.dirname(target), { recursive: true });
    const source = enabled ? shortcuts : marker;
    if (!exists || fs.readFileSync(target, "utf8") !== source)
      fs.writeFileSync(target, source);
    IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
      filepath: `${name}/${filename}`,
      groupName: name,
      project: mod.modResults,
    });
    return mod;
  });
};
